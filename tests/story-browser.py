"""Chromium interaction checks using local inline assets (no remote network required).
Managed environments can block navigation even to localhost; history writes are
captured here. Actual hosting/deep links must also be smoke-tested separately.
Run: python tests/story-browser.py
"""
from pathlib import Path
import json,re,os,shutil
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]/'public'
OUT=Path(os.environ.get('STORY_TEST_OUTPUT',str(ROOT.parent/'test-results'/'story')));OUT.mkdir(parents=True,exist_ok=True)
source=(ROOT/'story.html').read_text()
scripts=re.findall(r'<script src="([^"?]+)[^"]*" defer></script>',source)
html=re.sub(r'<script[^>]*></script>','',source)
html=re.sub(r'<link rel="stylesheet"[^>]*>',lambda _: '<style>'+(ROOT/'story.css').read_text()+'</style>',html)
checks=[];errors=[]
def check(value,name):
 assert value,name
 checks.append(name)
def start(browser,width=1440):
 page=browser.new_page(viewport={'width':width,'height':1000 if width>700 else 844},device_scale_factor=1)
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(html)
 page.evaluate("window.__history=[];history.replaceState=(...a)=>window.__history.push(a);history.pushState=(...a)=>window.__history.push(a)")
 for script in scripts:page.add_script_tag(content=(ROOT/script).read_text())
 return page
with sync_playwright() as p:
 executable=os.environ.get('CHROMIUM') or shutil.which('chromium') or shutil.which('chromium-browser')
 browser=p.chromium.launch(**({'executable_path':executable} if executable else {}),headless=True,args=['--no-sandbox'])
 page=start(browser)
 check(page.evaluate('HistoryStory.data.events.length')>500,'Real merged research loaded')
 check(page.locator('.period-row').count()==6,'Six collapsed groups by default')
 check(page.locator('.record-detail:visible').count()==0,'No expanded records on initial load')
 check(not page.locator('#storyDrawer').is_visible(),'Drawer closed on initial load')
 check(page.locator('[data-subject]').count()==10,'Nine subjects and All')
 page.screenshot(path=str(OUT/'story-timeline-desktop.png'),full_page=True)
 opener=page.locator('[data-open-subject]').first
 key=opener.get_attribute('data-open-subject');opener.click()
 check(page.locator('#storyDrawer').is_visible(),'Subject opens drawer')
 check(page.locator('.record-toggle').count()<=8,'Record list initially bounded')
 check(page.locator('.record-detail:visible').count()==0,'Records initially collapsed inside drawer')
 first=page.locator('[data-open-event]').first;eid=first.get_attribute('data-open-event');first.click()
 check(page.locator('.record-detail:visible').count()==1,'One expanded record')
 check(page.locator('.record-detail:visible').inner_text()!='','Historical explanation visible')
 check(page.locator('.record-detail:visible .source-list').count()==1,'Evidence shown on expanded record')
 urls=page.locator('.record-detail:visible .record-links a').evaluate_all('(links)=>links.map(a=>a.getAttribute("href"))')
 check(len(urls)==3,'Map, comparison and technology actions')
 check(urls[0].startswith('compare.html?year='),'Comparison link carries date')
 check(urls[1].startswith('index.html?year='),'Map link carries date')
 check(urls[2].endswith('#technology'),'Technology link targets existing explorer')
 check(page.evaluate('window.__history.at(-1)[2]').find('event=')>=0,'Selected event written to sharing URL')
 page.screenshot(path=str(OUT/'story-timeline-details.png'))
 first=page.locator('[data-open-event]').first;first.click()
 check(page.locator('.record-detail:visible').count()==0,'Click same record collapses')
 page.keyboard.press('Escape');page.wait_for_timeout(50)
 check(not page.locator('#storyDrawer').is_visible(),'Escape closes native drawer')
 check(page.evaluate('document.activeElement.dataset.openSubject')==key,'Keyboard focus returns to capsule')
 check(page.locator('[data-open-subject][aria-expanded=true]').count()==0,'Expanded state resets')
 page.locator('[data-subject="technology"]').click()
 check(page.evaluate('HistoryStory.state.subject')=='technology','Subject filter updates state')
 check(all(v=='technology' for v in page.locator('.subject-capsule').evaluate_all('(x)=>x.map(a=>a.dataset.openSubject)')),'Only selected subject shown')
 page.locator('[data-subject="all"]').click()
 page.locator('[data-story-mode="subjects"]').click()
 check(page.locator('.subject-tile').count()==9,'Subject overview shows nine families')
 page.locator('.subject-tile:not([disabled])').first.click()
 check(page.locator('#storyDrawer').is_visible(),'Subject overview opens same drawer')
 if page.locator('#moreDrawerRecords').is_visible():
  count=page.locator('.record-toggle').count();page.locator('#moreDrawerRecords').click()
  check(page.locator('.record-toggle').count()>count,'More records reveals next batch')
 page.locator('#closeStoryDrawer').click()
 page.locator('[data-story-mode="story"]').click()
 check(page.locator('.period-row').count()<=6,'Return to Story stays compact')
 page.locator('#moreFilters summary').click()
 page.locator('#storyRegion').select_option('East Asia')
 check(page.evaluate('HistoryStory.state.region')=='East Asia','Region state updates')
 check('region=East+Asia' in page.evaluate('window.__history.at(-1)[2]'),'Region retained in share URL')
 page.locator('#storyRegion').select_option('all')
 page.locator('#storyEntity').select_option('abbasid')
 check(page.evaluate('HistoryStory.state.entity')=='abbasid','Entity filter updates')
 page.locator('#storyType').select_option('empire')
 check(page.evaluate('HistoryStory.state.type')=='empire','Empire filter updates')
 page.locator('#resetStory').click()
 check(page.evaluate('HistoryStory.state.type')=='all' and page.evaluate('HistoryStory.state.entity')=='all','Reset clears filters')
 page.locator('#storyDensity').select_option('icons')
 check(page.locator('#storyTimeline').get_attribute('class')=='compact','Compact icon option')
 check(page.locator('.capsule-label:visible').count()==0,'Compact labels visually hidden')
 check(page.locator('[data-open-subject]').first.get_attribute('aria-label') is not None,'Icon accessible name retained')
 page.locator('#storyGroup').select_option('1')
 check(page.evaluate('HistoryStory.state.group')==1,'Exact-year grouping')
 page.locator('#storySpan').select_option('1000')
 check(page.evaluate('HistoryStory.state.span')==1000,'Time window updates')
 page.locator('#nextGroups').click()
 check(page.evaluate('HistoryStory.state.page')==1,'Next period page')
 page.locator('#previousGroups').click()
 check(page.evaluate('HistoryStory.state.page')==0,'Previous period page')
 page.locator('#resetStory').click()
 page.locator('#storySearch').fill('NoMatchingRecordsForThisSearch');page.wait_for_timeout(250)
 check(page.locator('.empty-story').is_visible(),'Empty result explained')
 page.locator('[data-reset]').click()
 check(page.locator('.period-row').count()>0 and page.locator('#storySearch').input_value()=='','Empty state reset recovers')
 page.locator('#storyYear').fill('500 BCE');page.locator('#storyYear').press('Enter')
 check(page.evaluate('HistoryStory.state.year')==-499,'Typed BCE normalized once')
 page.locator('#storyYear').fill('1 BCE');page.locator('#storyYear').press('Enter')
 check(page.evaluate('HistoryStory.state.year')==0,'Year zero preserved')
 page.locator('#storyYear').fill('0 CE');page.locator('#storyYear').press('Enter')
 check(page.evaluate('HistoryStory.state.year')==0,'Invalid year cannot corrupt state')
 check(not page.locator('#storyYear').evaluate('(x)=>x.checkValidity()'),'Invalid CE zero reports validity error')
 page.locator('#storyYear').fill('1200 CE');page.locator('#storyYear').press('Enter')
 check(page.evaluate('HistoryStory.state.year')==1200,'Return to CE')
 page.locator('#laterStory').click();check(page.evaluate('HistoryStory.state.year')==1700,'Forward window')
 page.locator('#earlierStory').click();check(page.evaluate('HistoryStory.state.year')==1200,'Back window')
 for _ in range(10):
  page.locator('#surpriseStory').click()
  check(page.locator('#storyDrawer').is_visible() and page.locator('.record-detail:visible').count()==1,'Randomiser chooses non-empty evidence')
  page.locator('#closeStoryDrawer').click()
 page.close()
 for width in [1440,1024,768,390,320]:
  mobile=start(browser,width)
  check(not mobile.evaluate('document.documentElement.scrollWidth>innerWidth'),f'No horizontal page overflow at {width}')
  mobile.locator('[data-open-subject]').first.click();mobile.locator('[data-open-event]').first.click()
  check(mobile.locator('#storyDrawer').is_visible(),f'Drawer opens at {width}')
  check(mobile.locator('#storyDrawer').bounding_box()['width']<=width,f'Drawer fits at {width}')
  if width==390:
   mobile.screenshot(path=str(OUT/'story-timeline-mobile-details.png'))
   mobile.locator('#closeStoryDrawer').click();mobile.screenshot(path=str(OUT/'story-timeline-mobile.png'),full_page=True)
  mobile.close()
 check(errors==[],'No JavaScript exceptions')
 browser.close()
report={'checks':len(checks),'passed':checks,'pageErrors':errors,'environment':'Chromium local inline assets. History API captured; public URL navigation not tested by this harness.'}
(OUT/'browser-report.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report,indent=2))
