import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const script=readFileSync('public/story-navigation.js','utf8');
const links=[];
const location={pathname:'/compare.html',search:'?year=800&civ=abbasid',hash:'',protocol:'https:'};
const context={location,window:{},document:{readyState:'loading',addEventListener(){},querySelectorAll(){return links;}},URLSearchParams};
vm.runInNewContext(script,context);
assert.equal(context.window.AtlasNavigation.href('story'),'story.html?year=800&entity=abbasid');
assert.equal(context.window.AtlasNavigation.href('map'),'index.html?year=800&civ=abbasid');
assert.equal(context.window.AtlasNavigation.href('compare'),'compare.html?year=800&civ=abbasid');
assert.equal(context.window.AtlasNavigation.href('technology'),'index.html?year=800&civ=abbasid#technology');
context.window.HistoryCompare={state:{year:850,selected:'tang'}};
assert.equal(context.window.AtlasNavigation.href('story'),'story.html?year=850&entity=tang');
delete context.window.HistoryCompare;
location.search='?year=-499&entity=rome';
assert.equal(context.window.AtlasNavigation.href('map'),'index.html?year=-499&civ=rome');
const map=readFileSync('public/app.js','utf8');
assert.match(map,/atlas-journey/);
assert.match(map,/window.AtlasNavigation.href\(view\)/);
const html=readFileSync('public/index.html','utf8');
assert.ok(html.indexOf('story-navigation.js')<html.indexOf('app.js?v='));
console.log('Cross-view history context navigation: passed');
