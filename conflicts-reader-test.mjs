/* Conflict explorer regression checks (pure filters, sensitive defaults, context links). */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
const context=vm.createContext({URLSearchParams});
vm.runInContext(read('./public/conflicts-model.js'),context,{filename:'conflicts-model.js'});
const m=context.HistoryConflictsModel;
const row=(id,start,end,extras={})=>({id,type:'conflict',hierarchy:'INDIVIDUAL_CONFLICT',title:id,summary:'Source evidence',region:'Europe',dateText:'Sourced window',participations:[],start,endExclusive:end,sensitive:false,links:[],parentIds:[],...extras});
const aceh=row('conf_aceh',1873,1915);
assert.equal(m.periodMatches(aceh,'modern'),true,'Starts in nineteenth-century band');
assert.equal(m.periodMatches(aceh,'contemporary'),true,'Conflict crossing 1900 must be visible in modern and contemporary period filters');
assert.equal(m.periodMatches(aceh,'medieval'),false);
assert.equal(m.periodMatches(row('late',1905,1912),'modern'),false);
assert.equal(m.periodMatches(row('missing',null,null),'undated'),true);
assert.equal(m.periodMatches(row('missing',null,null),'bce'),false,'Never infer an exact point from an uncertain source');
assert.equal(m.periodMatches(row('unknownend',1873,null,{endStatus:'UNKNOWN'}),'contemporary'),false,'Unknown end must not imply open-ended conflict');
assert.equal(m.periodMatches(row('ongoing',2022,null,{endStatus:'ONGOING',observedThrough:'2026-09-30'}),'contemporary'),true);
assert.equal(m.periodMatches(row('ongoing',2022,null,{endStatus:'ONGOING',observedThrough:'2026-09-30'}),'modern'),false);
const crisis=row('crisis',1859,1873,{hierarchy:'CRISIS',links:['event_pig']});
const pig=row('event_pig',1859,1860,{type:'event',parentIds:['crisis']});
const bad=row('sensitive',1994,1995,{type:'event',sensitive:true,parentIds:['crisis']});
assert.deepEqual([...m.related(crisis,[crisis,pig,bad])].map(x=>x.id),['event_pig','sensitive']);
assert.equal(m.kindOf(crisis),'context');assert.equal(m.kindOf(pig),'event');
assert.equal(m.matches(bad,{kind:'all',era:'all',search:'',sensitive:false}),false);
assert.equal(m.matches(bad,{kind:'all',era:'all',search:'',sensitive:true}),true);
assert.deepEqual(JSON.parse(JSON.stringify(m.safeFilters('?era=modern&record=conf_aceh&kind=individual&sensitive=1'))),{kind:'individual',era:'modern',search:'',sensitive:false,page:0,record:'conf_aceh'},'Deep links cannot opt into sensitive research');
assert.equal(m.label(0),'1 BCE');assert.equal(m.label(-499),'500 BCE');assert.equal(m.label(null),'Undated / uncertain');
const html=read('./public/conflicts.html');
for(const s of ['conflicts-model.js','conflicts-data.js','conflicts-app.js','id="conflictNotice"'])assert.ok(html.includes(s),'Missing conflict UI: '+s);
const app=read('./public/conflicts-app.js');
for(const s of ['data-focus-record','related-records','setURL(',"'popstate'",'state.sensitive'])assert.ok(app.includes(s),'Missing conflict behavior: '+s);
const story=read('./public/story-app.js');assert.ok(story.includes('conflicts.html?record='),'Story conflict milestones must deep-link to the original research record');
console.log('PASS Conflicts explorer polish: dated overlap, uncertain end, related navigation, BCE boundary, sensitive gating and deep links');