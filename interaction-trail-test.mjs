import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=path=>fs.readFileSync(new URL(path,import.meta.url),'utf8');
const evidenceCode=read('./public/interaction-evidence.js');
const ui=read('./public/interactions.js');
const html=read('./public/interactions.html');
const css=read('./public/interactions.css');
const context=vm.createContext({});
vm.runInContext(evidenceCode,context);
const evidence=context.AtlasInteractionEvidence;
const a={key:'a',year:90,participants:['rome','parthia'],type:'Trade',title:'A'};
const b={key:'b',year:100,participants:['rome','han'],type:'Knowledge',title:'B'};
const c={key:'c',year:110,participants:['rome','parthia'],type:'Diplomacy',title:'C'};
const items=[a,b,c];
assert.equal(evidence.move(items,null,1)?.key,'a','Empty selection defaults to first record');
assert.equal(evidence.move(items,null,-1)?.key,'c','Back from missing selection defaults to last record');
assert.equal(evidence.move(items,'a',-1)?.key,'a','At start, previous stays at first');
assert.equal(evidence.move(items,'c',1)?.key,'c','At end, next stays at last');
assert.equal(evidence.move(items,'b',1)?.key,'c');
assert.equal(evidence.move(items,'b',-1)?.key,'a');
assert.equal(evidence.move([],null,1),null,'Empty filters cannot play');
const societies=new Map([['rome',{name:'Rome'}],['parthia',{name:'Parthia'}],['han',{name:'Han'}]]);
const all=evidence.filter(items,{start:80,end:120,focus:'rome',societyNames:societies});
const focused=evidence.filter(items,{start:80,end:120,focus:'rome',partner:'parthia',societyNames:societies});
assert.equal(all.length,3);
assert.equal(focused.length,2);
assert.equal(evidence.partners(all,'rome',societies).length,2,'The contextual network retains both partners');
assert.match(html,/id="interactionPreviousRecord"/);
assert.match(html,/id="interactionNextRecord"/);
assert.match(html,/id="interactionPlayRecords"/);
assert.match(html,/id="interactionDetailPanel"/);
assert.match(html,/Read selected evidence/);
assert.match(css,/interaction-network-svg\s*\{width:760px;min-width:760px/,'Mobile SVG network remains scrollable and legible');
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(ui,/state\.focus\?contextualRecords\(\):rows/,'Partner filtering must not hide the wider focused network');
assert.match(ui,/query\.set\('event',state\.event\)/,'Individual record context survives share links');
assert.match(ui,/motionReduced\(\)/,'Reduced-motion users do not get autoplay');
assert.match(ui,/document\.hidden/,'Playback stops when the tab becomes hidden');
assert.match(ui,/scrollIntoView/,'Selected mobile records bring evidence into view');
assert.match(ui,/networkScroller\.scrollLeft/,'Mobile network position is preserved between evidence selections');
assert.match(ui,/previouslyFocusedSociety!==state\.focus/,'Changing society recentres the mobile network');
assert.match(ui,/event:params\.get\('event'\)/,'Shared direct links restore their selected record');
new vm.Script(ui,{filename:'interactions.js'});
console.log('PASS interaction time trail: chronology, boundary handling, wider network context, mobile reading and safe playback');
