import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import vm from 'node:vm';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
const raw=read('./public/modern-v2-data.js');
const base64=raw.match(/ATLAS_MODERN_V2_GZIP = '([^']+)'/)?.[1];
assert.ok(base64,'Versioned modern v2 gzip archive is present');
const data=JSON.parse(gunzipSync(Buffer.from(base64,'base64')));
assert.equal(data.quality.pack_id,'wha_1501_2026_priority_v2');
assert.deepEqual([data.metadata.start_year,data.metadata.end_year_exclusive],[1501,2027]);
assert.equal(data.quality.independently_corroborated_claims,0);
assert.equal(data.tables.events.length,97);
assert.equal(data.tables.technology_developments.length,28);
assert.equal(data.tables.conflicts.length,18);
assert.equal(data.tables.claims.length,123);
assert.equal(data.tables.source_register.length,90);
assert.equal(data.tables.societies.length,90);
assert.equal(data.tables.discovery_cards.length,10);
assert.equal(data.tables.historical_maps.length,0,'Do not invent historical map images');
assert.equal(data.tables.campaign_routes.length,0,'No reconstructed itineraries');
assert.equal(data.tables.baseline_review_queue.length,47,'Earlier research records remain queued, not deleted');
assert.ok(data.tables.societies.every(s=>s.map_polity_bar_allowed===false),'Actor references must never create spurious polity bars');
const baseline=new Set(data.tables.entity_aliases.map(r=>r.id));
assert.ok(baseline.size>100);
const c=vm.createContext({URL,console});c.window=c;
vm.runInContext(read('./public/modern-v2-model.js'),c);
const model=c.AtlasModernV2;
const pack=model.decode(data);
const result=model.list(pack,{type:'events',limit:200});
assert.ok(result.count>60);
assert.ok(result.rows.every(x=>x.default_discovery!==false));
assert.ok(result.rows.every(x=>x.content_level!=='DISTURBING_NON_GRAPHIC'));
const all=model.list(pack,{type:'events',limit:200,includeSensitive:true});
assert.equal(all.count,97);
assert.ok(model.sourceLinks(pack,data.tables.events[0]).length>0);
assert.ok(model.reviewedClaims(pack,data.tables.events[0]).length>0);
const exact=data.tables.events.filter(model.isPreciseEvent);
assert.ok(exact.length>0);
assert.ok(data.tables.events.some(e=>e.temporal_kind!=='POINT'));
assert.ok(!model.isPreciseEvent(data.tables.events.find(x=>x.temporal_kind!=='POINT')));
assert.throws(()=>model.decode({tables:{},quality:{pack_id:'bad'}}));
const html=read('./public/discover.html');
for(const id of ['modernV2Evidence','modernV2Type','modernV2Search','modernV2Sensitive','modernV2Status','modernV2Cards'])assert.ok(html.includes('id="'+id+'"'));
assert.ok(!html.includes('<script src="modern-v2-data.js'),'Canonical archive must load only on user request');
console.log('PASS modern v2: canonical 97 events, 28 technology observations, 18 conflicts, 123 claims, 90 sources; source and content guardrails');
