import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
const context=vm.createContext({});
vm.runInContext(read('./public/conflicts-data.js'),context,{filename:'conflicts-data.js'});
vm.runInContext(read('./public/conflicts-story.js'),context,{filename:'conflicts-story.js'});
const {raw,story}=vm.runInContext('({raw:ATLAS_CONFLICTS_DATA,story:ATLAS_CONFLICT_STORY_EVENTS})',context);
const full=JSON.parse(read('./research/conflicts/structured-pack.json')).tables;
assert.equal(full.conflicts.length,45);
assert.equal(full.battles_and_sieges.length,22);
assert.equal(full.historical_events.length,13);
assert.equal(full.sources.length,86);
assert.equal(full.claims.length,399);
assert.equal(full.source_claims.length,514);
assert.equal(full.conflict_participations.length,90);
assert.equal(raw.records.length,113);
assert.equal(new Set(raw.records.map(r=>r.id)).size,raw.records.length);
assert.ok(raw.records.every(r=>r.sources.every(s=>/^https:\/\//.test(s.url))));
assert.equal(raw.records.filter(r=>r.type==='conflict'&&r.hierarchy==='INDIVIDUAL_CONFLICT').length,31);
assert.ok(raw.records.find(r=>r.id==='conf_ukraine').endExclusive===null,'Ongoing end remains null');
assert.equal(raw.records.find(r=>r.id==='event_holocaust').sensitive,true,'Sensitive historical event is gated');
assert.equal(raw.records.find(r=>r.id==='story_cher').sensitive,true,'Unsupported anecdote is not ordinary default discovery');
assert.ok(story.length>30&&story.length<90);
assert.ok(story.every(r=>Number.isSafeInteger(r.year)&&r.endExclusive>r.year&&r.kind==='War & conflict'&&r.sourceUrls.every(u=>u.startsWith('https://'))));
assert.ok(!story.some(r=>r.id.includes('holocaust')||r.id.includes('rwanda_genocide')||r.id.includes('srebrenica')),'Sensitive events are opt-in only');
assert.ok(!story.some(r=>r.year===undefined||r.year===null));
const unknown=full.conflicts.find(r=>r.id==='conf_lagash_umma');assert.equal(unknown.temporal.start_year,null);
assert.ok(!story.some(r=>r.id==='gc-conf_lagash_umma'),'Unknown date not invented');
assert.ok(!story.some(r=>r.id==='gc-battle_qadesh'),'Disputed Qadesh/Kadesh date stays in research until reconciled');
const qadesh=raw.records.find(r=>r.id==='battle_qadesh');assert.equal(qadesh.start,-1274,'Astronomical year is preserved in source explorer');
assert.ok(!('longitude' in raw.records[0]),'No fabricated map geometries');
const h=read('./public/conflicts.html');
assert.ok(h.includes('conflicts-data.js')&&h.includes('conflicts-app.js'));
assert.ok(h.includes('id="sensitive"'));
const source=read('./public/story.html');
assert.ok(source.includes('conflicts-story.js'),'Story Timeline imports general conflict milestones');
assert.ok(source.includes('href="conflicts.html"'),'Conflict exploration navigation exists');
assert.ok(read('./public/story-app.js').includes('ATLAS_CONFLICT_STORY_EVENTS'));
console.log('PASS Conflicts v0.11',JSON.stringify({records:raw.records.length,defaultRecords:raw.records.filter(r=>!r.sensitive).length,storyEvents:story.length,fullSourceClaims:full.source_claims.length}));