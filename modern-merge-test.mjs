import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL(p,import.meta.url),'utf8');
const ctx=vm.createContext({});
const base=['data.js','entity-types.js','research-sources.js','research-events-500a.js','research-events-500b.js','research-events-modern.js','research-tech-records.js','research-civilisations.js','research-apply.js','research-1000-1499.js','research-1000-1499-apply.js','research-1500-2026-data.js','research-1500-2026-apply.js','tech-data.js','tech-extensions.js','research-tech.js','research-1000-1499-tech.js','research-1500-2026-tech.js'];
for(const file of base)vm.runInContext(read('./public/'+file),ctx,{filename:file,timeout:12000});
const x=vm.runInContext('({c:CIVILISATIONS,e:EVENTS,t:TECHNOLOGIES,raw:ATLAS_MODERN_PACK,events:ATLAS_MODERN_EVENTS,stats:ATLAS_MODERN_STATS,added:ATLAS_MODERN_TECH_IMPORTED,unmapped:ATLAS_MODERN_TECH_UNMAPPED})',ctx);
assert.equal(x.raw.societies.length,187);
assert.equal(x.raw.events.length,173);
assert.equal(x.raw.technologies.length,53);
assert.equal(x.raw.technology_developments.length,87);
assert.equal(x.raw.source_register.length,117);
assert.equal(x.raw.source_claims.length,undefined,'Claim table archived separately, not loaded into the browser');
assert.equal(x.events.length,173);
assert.equal(x.stats.added+x.stats.reused+x.stats.researchOnly,187);
assert.equal(x.added+x.unmapped,87);
assert.equal(new Set(x.c.map(c=>c.id)).size,x.c.length,'Unique society identities');
const valid=new Set(x.c.map(c=>c.id));
assert(x.e.every(e=>valid.has(e.civ)),'No invalid linked events');
assert(x.events.every(e=>e.endExclusive>e.year&&Array.isArray(e.sourceIds)),'Research date windows and sources retained');
assert(x.t.flatMap(t=>t.appearances).every(a=>valid.has(a.civ)),'No invalid technology-to-society mapping');
assert(x.c.find(c=>c.id==='aboriginal').kind==='overview','Broad Indigenous Australian entry remains an overview');
assert(read('./public/compare.js').includes('ATLAS_MODERN_EVENTS'),'Compare includes structured modern events');
for(const p of ['./public/index.html','./public/compare.html'])assert(read(p).includes('research-1500-2026-apply.js'),'Missing adapter from '+p);
assert(read('./public/index.html').includes('research-1500-2026-tech.js'));
assert(fs.existsSync(new URL('./research/1500-2026/source-pack.json',import.meta.url)));
console.log('PASS modern import',x.c.length,'entities',x.e.length,'events',x.events.length,'modern events',x.added,'technology records attached',x.unmapped,'retained research-only');