import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const dir=new URL('./public/',import.meta.url);
const read=name=>fs.readFileSync(new URL(name,dir),'utf8');
const ctx=vm.createContext({});
vm.runInContext(read('data.js')+'\n'+read('entity-types.js')+'\nthis.entities=CIVILISATIONS;',ctx);
const all=ctx.entities;
const empires=all.filter(c=>c.kind==='empire');
const societies=all.filter(c=>c.kind==='society');
const overviews=all.filter(c=>c.kind==='overview');
assert.equal(all.length,empires.length+societies.length+overviews.length);
assert.ok(empires.some(c=>c.id==='rome'),'Roman empire listed in Empire timeline');
assert.ok(societies.some(c=>c.id==='athens'),'Athens in Society timeline');
assert.ok(overviews.some(c=>c.id==='aboriginal'),'Australian broad cultural overview not dated as one polity');
assert.ok(!empires.some(c=>c.id==='aboriginal'));
assert.ok(!societies.some(c=>c.id==='aboriginal'));
for(const e of empires)assert.ok(e.start<=e.end,`Dated empire ${e.id}`);
for(const e of societies)assert.ok(e.start<=e.end,`Dated society ${e.id}`);
const html=read('index.html');
for(const id of ['culturalOverviewList','timelineRows','parallelCount','civilisationList','yearSlider'])assert.ok(html.includes('id="'+id+'"'),id);
for(const c of ['all','society','empire'])assert.ok(html.includes('data-catalogue="'+c+'"'),c);
assert.ok(html.includes('entity-types.js?v=0.4.0'),'Classification loaded before main atlas script');
console.log(`PASS: ${societies.length} societies, ${empires.length} empires, ${overviews.length} undated overviews, controls present.`);