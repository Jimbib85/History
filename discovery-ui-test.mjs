import assert from 'node:assert/strict';
import fs from 'node:fs';import vm from 'node:vm';
const read=x=>fs.readFileSync(new URL(x,import.meta.url),'utf8');
const html=read('./public/discover.html');const nodes=new Map();
function fake(id=''){return {id,innerHTML:'',textContent:'',value:'',href:'',disabled:false,dataset:{},listeners:new Map(),
 addEventListener(k,f){this.listeners.set(k,f)},setAttribute(k,v){this[k]=v},blur(){},focus(){},closest(){return null}}}
for(const match of html.matchAll(/id="([^"]+)"/g))nodes.set(match[1],fake(match[1]));
const years=[200,1600,1800].map(y=>{const x=fake();x.dataset.snapshot=String(y);return x});
const location={href:'https://atlas.test/discover.html?journey=daily-life&step=0&year=1600',search:'?journey=daily-life&step=0&year=1600'};
const written=[];
const document={activeElement:null,getElementById:id=>nodes.get(id),querySelectorAll:s=>s==='[data-snapshot]'?years:[]};
const history={replaceState(_a,_b,url){written.push(url)}};
const context=vm.createContext({URL,URLSearchParams,document,location,history,console});
context.window=context;
for(const [,p] of html.matchAll(/<script src="([^"?]+)/g))vm.runInContext(read('./public/'+p),context,{filename:p});
const app=context.AtlasDiscoveryUI;
assert.ok(app);
assert.equal(app.state.journey,'daily-life');assert.equal(app.state.step,0);
assert.match(nodes.get('journeyChoices').innerHTML,/data-journey="craft-exchange"/);
assert.match(nodes.get('guideStep').innerHTML,/Urban housing across Roman social strata/);
assert.equal(nodes.get('prevStep').disabled,true);
assert.match(nodes.get('snapshotSummary').textContent,/1600 CE/);
assert.match(nodes.get('snapshotCards').innerHTML,/entry-card/);
assert.match(nodes.get('snapshotCompare').href,/year=1600/);
nodes.get('nextStep').listeners.get('click')();
assert.equal(app.state.step,1);assert.ok(written.at(-1).includes('step=1'));
nodes.get('journeyChoices').listeners.get('click')({target:{closest:q=>q==='[data-journey]'?{dataset:{journey:'craft-exchange'}}:null}});
assert.equal(app.state.journey,'craft-exchange');assert.equal(app.state.step,0);
assert.match(nodes.get('guideStep').innerHTML,/Punic port commerce/);
nodes.get('randomDiscovery').listeners.get('click')();
assert.ok(app.state.random);const previous=app.state.random.id;
assert.ok(app.model.src(app.state.random).length>0);
nodes.get('randomDiscovery').listeners.get('click')();
assert.notEqual(app.state.random.id,previous,'Random should avoid immediate repeats');
assert.ok(written.at(-1).includes('record='));
years[0].listeners.get('click')();
assert.equal(app.state.year,200);
assert.match(nodes.get('snapshotSummary').textContent,/200 CE/);
nodes.get('snapshotYear').listeners.get('change')({target:{value:'500 BCE'}});
assert.equal(app.state.year,-499);
assert.equal(app.parseYear('1 BCE'),0);
assert.equal(app.parseYear('0 CE'),null);
assert.ok(html.includes('discovery-data.js')&&!html.includes('research-classical-data.js'),'Only lightweight index loads in discovery page');
assert.ok(read('./public/story.html').includes('href="discover.html"'));
assert.ok(read('./public/index.html').includes('id="discoverLink"'));
assert.match(read('./public/app.js'),/discoverLink/);
console.log('PASS discovery UI: initial render, accessible journey navigation, source-linked random, date changes, and compact script loading');
