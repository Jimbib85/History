import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {inflateSync} from 'node:zlib';
import vm from 'node:vm';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const data=read('./public/classical-reviewed-data.js');
const b64=data.match(/ATLAS_CLASSICAL_REVIEW_DEFLATE_BASE64 = '([^']+)'/)?.[1];
assert.ok(b64,'Compressed classical research payload present');
const payload=JSON.parse(inflateSync(Buffer.from(b64,'base64')).toString('utf8'));
assert.deepEqual(payload.boundary,[-499,1,501],'BCE and CE periods are adjacent, not overlapping');
assert.equal(payload.records.length,72,'All review-backed typed records imported');
assert.deepEqual([...new Set(payload.records.map(x=>x.id))].length,72,'No shared classical IDs duplicated');
const byKind=Object.groupBy(payload.records,r=>r.kind);
assert.equal(byKind.event.length,33);
assert.equal(byKind.technology.length,20);
assert.equal(byKind.culture.length,14);
assert.equal(byKind.map.length,2);
assert.equal(byKind.geography.length,3);
assert.equal(payload.records.filter(r=>r.batches?.length>1).length,8,'Shared cross-batch identities merged');
assert.ok(payload.records.every(r=>r.summary?.length&&r.claimIds?.length&&r.sources?.length),'Only review-backed excerpts and sources');
assert.ok(payload.records.every(r=>r.status!=='NEEDS_REVIEW'));
assert.ok(payload.records.every(r=>r.sources.every(s=>s.startsWith('https://'))));
const context=vm.createContext({});
context.window=context;
vm.runInContext(read('./public/classical-reviewed-model.js'),context);
const model=context.AtlasClassicalReviewed;
const pack=model.fromJSON(payload);
assert.equal(model.browse(pack.records,{kind:'map'}).length,2);
assert.equal(model.browse(pack.records,{batch:'500 BCE–1 BCE',kind:'event',limit:100}).length>0,true);
const roman=pack.records.find(r=>r.id==='evt_vesuvius_eruption');
assert.ok(roman&&model.isPoint(roman));
assert.equal(model.temporal(roman),'79 CE');
const conventional=pack.records.find(r=>r.id==='evt_parthian_arsacid_emergence');
assert.ok(model.isPoint(conventional));
assert.match(model.temporal(conventional),/conventional era marker/);
const window=pack.records.find(r=>r.id==='evt_roman_indian_ocean_trade');
assert.ok(window&&!model.isPoint(window));
assert.match(model.temporal(window),/not an exact event date/);
const noDate=pack.records.find(r=>r.id==='evt_budj_bim_continuity');
assert.ok(!model.isPoint(noDate));
assert.match(model.temporal(noDate),/no construction date assigned/);
assert.equal(model.yearText(0),'1 BCE');
assert.equal(model.yearText(-499),'500 BCE');
assert.equal(model.browse(pack.records,{query:'Mawangdui',limit:100}).length>=3,true);
assert.throws(()=>model.fromJSON({records:[{id:'x',status:'NEEDS_REVIEW',summary:'Unreviewed',claimIds:['a']}]}));
const html=read('./public/discover.html');
assert.ok(html.includes('classical-reviewed-model.js'));
assert.ok(html.includes('classical-reviewed-view.js'));
assert.ok(!html.includes('<script src="classical-reviewed-data.js'),'Payload must only be loaded when opened');
assert.ok(read('./public/classical-reviewed-view.js').includes("document.createElement('script')"));
for(const id of ['classicalEvidence','classicalCards','classicalKind','classicalBatch','classicalSearch','classicalMore'])assert.ok(html.includes('id="'+id+'"'));
console.log('PASS v0.20 reviewed classical claims: 72 deduplicated, 8 shared IDs, 17 precise/conventional points, provenance retained, no uncertain midpoint or unreviewed promotion');
