import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('./public/data.js',import.meta.url),'utf8')+'\n'+fs.readFileSync(new URL('./public/entity-types.js',import.meta.url),'utf8');
const sandbox=vm.createContext({});
vm.runInContext(source+'\nthis.dataset={societies:CIVILISATIONS,events:EVENTS}',sandbox);
const data=sandbox.dataset;
const entities=data.societies.filter(c=>c.kind!=='overview');
assert.ok(entities.length>=50,'Society/empire data available');
assert.ok(data.events.length>=45,'Event comparison data available');
assert.ok(entities.every(c=>Number.isFinite(c.start)&&Number.isFinite(c.end)&&c.start<=c.end),'All compared dates valid');
assert.ok(entities.some(c=>c.kind==='society')&&entities.some(c=>c.kind==='empire'),'Two classification types');
const html=fs.readFileSync(new URL('./public/compare.html',import.meta.url),'utf8');
const js=fs.readFileSync(new URL('./public/compare.js',import.meta.url),'utf8');
for (const id of ['comparisonChart','compareRegion','compareType','compareYear','compareSlider','compareSpan','compareLimit','compareSearch','selectedName','mapLink','randomComparison','resetCompare','pinCompare']) assert.ok(html.includes(`id="${id}"`),`Missing compare control ${id}`);
for (const mode of ['overlap','eras','regions','events'])assert.ok(html.includes(`data-mode="${mode}"`)&&js.includes(mode),`Missing view ${mode}`);
for (const resource of ['data.js','entity-types.js','compare.js','compare.css'])assert.ok(html.includes(resource),`Missing asset ${resource}`);
const active1200=entities.filter(c=>c.start<=1200&&c.end>=1200);
assert.ok(active1200.length>5,'Meaningful comparison sample around 1200 CE');
assert.ok(!active1200.some(c=>c.id==='aboriginal'),'Undated cultural overviews should not appear on political timeline');
console.log(`PASS Compare: ${entities.length} dated entities, ${data.events.length} events, 4 modes, 12 controls, BCE/CE and type filters.`);